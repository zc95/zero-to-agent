# 示例 6：用官方小结里的签名复习三种参数。
# 知识点：形参名只供函数内部使用时，可以限定为仅位置，以后改名也不影响
# 调用方。形参名能说明值的含义时，可以限定为仅关键字，让调用更清楚。
# 教程只给了签名，这里加 pass 作为函数体。
def f(pos1, pos2, /, pos_or_kwd, *, kwd1, kwd2):
    pass


# 题目：写出一次有效调用，把 1、2、3、4、5 依次传给这五个形参。
# 我的答案：f(1,2,3,kwd1=4,kwd2=5)或者f(1,2,pos_or_kwd=3,kwd1=4,kwd2=5)
# 标准答案：f(1, 2, 3, kwd1=4, kwd2=5) 或 f(1, 2, pos_or_kwd=3, kwd1=4, kwd2=5)。
# 解析：1 和 2 对应 / 左边的 pos1、pos2，按位置传。3 对应中间的 pos_or_kwd，两种传法都行。
# 4 和 5 对应 * 右边的 kwd1、kwd2，调用时要写出参数名。
