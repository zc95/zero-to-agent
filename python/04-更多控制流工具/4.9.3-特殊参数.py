# 4.9.3 特殊参数｜官方示例
# https://docs.python.org/zh-cn/3.13/tutorial/controlflow.html#special-parameters
# 参数列表中，/ 左边只能按位置传，裸 * 右边只能按名字传。
# 两个标记之间的参数可以用任一种传法。/ 和 * 本身都不接收值。
# 每个示例下方有一道题，在空白的「我的答案：」后作答。


# ----------------------------------------------------------------------
# 示例 1：位置或关键字参数。
# 知识点：普通形参 arg 可以接收位置实参，也可以接收同名的关键字实参。
def standard_arg(arg):
    print(arg)


standard_arg(2)
standard_arg(arg=2)


# 题目：两次调用分别用了哪种传法？输出一样吗？
# 我的答案：第一次用的位置参数，第二次用的关键字参数，输出一样
# 标准答案：standard_arg(2) 按位置传，standard_arg(arg=2) 按名字传，两次都打印 2。
# 解析：普通形参 arg 支持两种传法。第一个调用按顺序把 2 分给 arg，第二个调用用参数名找到 arg。


# ----------------------------------------------------------------------
# 示例 2：仅限位置参数。
# 知识点：/ 左边的形参只能按位置传，不能用它的名字传值。
def pos_only_arg(arg, /):
    print(arg)


pos_only_arg(1)
# pos_only_arg(arg=1)  # 故意报错，可单独取消注释验证。


# 题目：第二种调用为什么报错？改成什么写法才有效？
# 我的答案：/ 左边是仅位置参数，但是你传的是关键字参数
# 标准答案：有效写法是 pos_only_arg(1)。pos_only_arg(arg=1) 会报 TypeError。
# 解析：/ 左边的 arg 只接受位置实参。把 1 放在第一个位置，Python 就能给 arg 赋值。


# ----------------------------------------------------------------------
# 示例 3：仅限关键字参数。
# 知识点：函数定义中的裸 * 表示后面的形参只能按名字传。
def kwd_only_arg(*, arg):
    print(arg)


# kwd_only_arg(3)  # 故意报错，可单独取消注释验证。
kwd_only_arg(arg=3)


# 题目：为什么直接传 3 会报错？哪一行给 arg 传值成功？
# 我的答案：因为*后面是仅关键字参数，你传了位置参数
# 标准答案：kwd_only_arg(arg=3) 成功给 arg 传值，打印 3。kwd_only_arg(3) 会报 TypeError。
# 解析：裸 * 右边的 arg 只接受关键字实参。写出 arg=3 后，Python 就能通过名字找到 arg。


# ----------------------------------------------------------------------
# 示例 4：同一个函数里使用三种形参。
# 知识点：pos_only 在 / 左边，standard 在 / 与 * 之间，kwd_only 在 * 右边。
# 先看每个形参允许哪种传法，再判断调用是否合法。
def combined_example(pos_only, /, standard, *, kwd_only):
    print(pos_only, standard, kwd_only)


# combined_example(1, 2, 3)
combined_example(1, 2, kwd_only=3)
combined_example(1, standard=2, kwd_only=3)
# combined_example(pos_only=1, standard=2, kwd_only=3)


# 题目：第一行和第四行各违反了哪条规则？中间两行的输出是否相同？
# 我的答案：
# 第一个：*后面是仅关键字参数，但是你传了位置参数3
# 第四个：/前面是仅位置参数，你传了关键字参数pos_only
# 中间两行实际输出一致
# 标准答案：第一行把 kwd_only 按位置传了，第四行把 pos_only 按名字传了。中间两行都打印 1 2 3。
# 解析：pos_only 只接受位置实参，kwd_only 只接受关键字实参。standard 支持两种传法，所以中间两行都给三个形参分别传了 1、2、3。


# ----------------------------------------------------------------------
# 示例 5：让仅限位置形参和 **kwds 的键同名。
# 知识点：调用里的 **{'name': 2} 相当于传入关键字实参 name=2。
# 先看 name 是否允许按名字传，再判断它会绑定给形参还是进入 kwds。
def foo(name, **kwds):
    return "name" in kwds


# foo(1, **{'name': 2})  # 故意报错，须在下面重新定义 foo 之前验证。


def foo(name, /, **kwds):
    return "name" in kwds


print(foo(1, **{"name": 2}))


# 题目：第一版 foo 为什么报错？加上 / 后，name 和 kwds 各收到什么？
# 我的答案：因为kwds有可能传的关键字参数name因为，第一个name已经传了1了；加上/之后name就肯定是位置参数，后面的name可以作为关键字参数传入
# 标准答案：第一版给 name 传了两个值，会报 TypeError。加上 / 后，name = 1，kwds = {"name": 2}，返回 True。
# 解析：**{"name": 2} 展开后是 name=2。第一版里，1 和 name=2 都匹配形参 name。
# 加上 / 后，只有位置上的 1 能绑定到 name，关键字 name=2 由 **kwds 收进字典。
# "name" in kwds 检查到字典有这个键，所以返回 True。


