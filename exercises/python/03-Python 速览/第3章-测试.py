# 第 30 题｜多重赋值
# 1. 多重赋值。先写出两次输出，再解释第二次更新用了哪些旧值。
a, b = 2, 5
print(a, b)  # 预测：2和5
a, b = b, a + b
print(a, b)  # 预测：5和7
# 解释：右边b是5，a是2+b是5=7，赋值给左边新的a和b，则a是5，b是7
# 评分：1 / 1
# 解析：先打印 2 5。右侧用旧值算出 b = 5 和 a + b = 7，再赋给左侧，第二次打印 5 7。

# 第 31 题｜循环体输出与退出时的值
# 2. while。循环体打印哪些数？循环结束时 n 是多少？
n = 1
while n < 5:
    print(n)
    n = n + 2
print(n)  # 预测：循环结束时n是5
# 循环体的输出：
# 1
# 3
# 评分：1 / 1
# 解析：先打印 1 并更新为 3，再打印 3 并更新为 5。5 < 5 为假，退出循环后由外面的 print 打印 5。

# 第 32 题｜在循环内更新两个变量
a, b = 1, 2
while a < 5:
    print(a, b)
    a, b = b, a + b
# 每轮输出：
# 1 2
# 2 3
# 3 5

# 结束时的 a 和 b：5 8

# 评分：1 / 1
# 解析：从 (1, 2) 开始，每轮先打印当前值，再用旧值更新。(1, 2) → (2, 3) → (3, 5) → (5, 8)，最后一次检查 5 < 5 为假，此时 a = 5，b = 8。

# 第 33 题｜用 while 倒数
